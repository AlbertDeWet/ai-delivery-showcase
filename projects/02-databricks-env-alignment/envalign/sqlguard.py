"""sqlguard - ALLOWLIST check for SQL inside a plan item (a blocking R2 rule in the linter).

The security decision is made on DuckDB's OWN parse tree, not on a home-made tokenizer:
  1. Fail closed on lexical constructs where a second lexer could disagree with DuckDB: any comment
     (`--`, `/*`), any `$` (dollar-quoted strings), escape strings (E'...').
  2. `duckdb.extract_statements` must see exactly ONE statement of an allowed type.
  3. The statement must have one of these exact shapes, writing the item's own object:
       CREATE [OR REPLACE] VIEW [IF NOT EXISTS] <obj> AS <query>
       CREATE [OR REPLACE] TABLE [IF NOT EXISTS] <obj> AS <query>
       CREATE TABLE <obj>(<plain column definitions>)
       INSERT INTO <obj> VALUES (...), ...
       DELETE FROM <obj> [WHERE <condition>]
       DROP TABLE|VIEW [IF EXISTS] <obj>
     (UPDATE, EXECUTE, SET, USE, COPY, ATTACH, CALL, PRAGMA ... are never generated by the tool and are rejected.)
  4. Every embedded query/condition/value list is serialised with `json_serialize_sql`. Anything it cannot
     serialise is rejected. The AST walk then allows only:
       - BASE_TABLE references to schema `core` or `_backup` (no catalog, plain names), or to a CTE name;
         a path or string as a table (replacement scan, e.g. FROM '/x.csv') is rejected,
       - no TABLE_FUNCTION at all (query, query_table, read_*, glob, range, json_execute_serialized_sql ...),
       - function calls only from ALLOWED_FUNCTIONS (operators are allowed).
The normaliser's tokenizer is used only for diffing, never for this decision.
"""
from __future__ import annotations

import json
import re
import threading

import duckdb

ALLOWED_SCHEMAS = frozenset({"core", "_backup"})

ALLOWED_FUNCTIONS = frozenset({
    # aggregates / windows
    "sum", "avg", "count", "count_star", "min", "max", "string_agg", "listagg", "group_concat", "median",
    "mode", "stddev", "stddev_samp", "stddev_pop", "variance", "var_samp", "var_pop", "any_value", "first",
    "last", "arg_min", "arg_max", "bool_and", "bool_or", "quantile_cont", "quantile_disc", "row_number",
    "rank", "dense_rank", "percent_rank", "cume_dist", "ntile", "lag", "lead", "first_value", "last_value",
    "nth_value",
    # conditional / casts
    "coalesce", "nullif", "ifnull", "greatest", "least", "try_cast", "error",
    # numbers
    "round", "abs", "floor", "ceil", "ceiling", "trunc", "sign", "sqrt", "power", "pow", "ln", "log", "log10",
    "exp", "mod",
    # strings
    "lower", "upper", "trim", "ltrim", "rtrim", "length", "substr", "substring", "replace", "concat",
    "concat_ws", "left", "right", "lpad", "rpad", "starts_with", "ends_with", "contains", "split_part",
    "strpos", "instr", "position", "regexp_replace", "regexp_matches", "regexp_extract", "prefix", "suffix",
    # dates
    "date_trunc", "date_diff", "datediff", "date_part", "datepart", "extract", "date_add", "date_sub",
    "strftime", "strptime", "current_date", "now", "today", "year", "month", "day", "quarter", "week",
    "dayofweek", "dayofyear", "hour", "minute", "second", "make_date", "last_day", "age", "epoch",
    "to_days", "to_months", "to_years", "to_hours", "to_minutes", "to_seconds", "to_weeks",
})

_FORBIDDEN_LEX = [
    (re.compile(r"--|/\*|\*/"), "comments are not allowed in plan SQL"),
    (re.compile(r"\$"), "'$' (dollar-quoted strings / parameters) is not allowed in plan SQL"),
    (re.compile(r"(?<![A-Za-z0-9_'])[eE]'"), "escape strings (E'...') are not allowed in plan SQL"),
]
_ID = r'(?:[A-Za-z_][A-Za-z0-9_]*|"(?:[^"]|"")+")'
_NAME = rf"(?P<name>{_ID}(?:\s*\.\s*{_ID})*)"
_SHAPES = [
    ("view", re.compile(rf"^\s*create\s+(?:or\s+replace\s+)?view\s+(?:if\s+not\s+exists\s+)?{_NAME}\s+as\s+"
                        rf"(?P<query>.+?)\s*;?\s*$", re.I | re.S)),
    ("ctas", re.compile(rf"^\s*create\s+(?:or\s+replace\s+)?table\s+(?:if\s+not\s+exists\s+)?{_NAME}\s+as\s+"
                        rf"(?P<query>.+?)\s*;?\s*$", re.I | re.S)),
    ("table", re.compile(rf"^\s*create\s+table\s+(?:if\s+not\s+exists\s+)?{_NAME}\s*"
                         r"\((?P<cols>[A-Za-z0-9_\s,()\"]*)\)\s*;?\s*$", re.I | re.S)),
    ("insert", re.compile(rf"^\s*insert\s+into\s+{_NAME}\s+values\s*(?P<values>\(.+\))\s*;?\s*$", re.I | re.S)),
    ("delete", re.compile(rf"^\s*delete\s+from\s+{_NAME}(?:\s+where\s+(?P<cond>.+?))?\s*;?\s*$", re.I | re.S)),
    ("drop", re.compile(rf"^\s*drop\s+(?:table|view)\s+(?:if\s+exists\s+)?{_NAME}\s*;?\s*$", re.I | re.S)),
]
_ALLOWED_TYPES = {"view": "CREATE", "ctas": "CREATE", "table": "CREATE", "insert": "INSERT",
                  "delete": "DELETE", "drop": "DROP"}

_local = threading.local()


def _con():
    c = getattr(_local, "con", None)
    if c is None:
        c = _local.con = duckdb.connect(config={"threads": 1})
    return c


def _canon_name(name: str) -> str:
    parts = re.findall(_ID, name)
    return ".".join(p[1:-1].replace('""', '"') if p.startswith('"') else p for p in parts).lower()


def _serialize(query: str) -> tuple[dict | None, str | None]:
    try:
        raw = _con().execute("SELECT json_serialize_sql(?)", [query]).fetchone()[0]
    except duckdb.Error as e:
        return None, f"DuckDB cannot serialise the query: {str(e).splitlines()[0][:120]}"
    tree = json.loads(raw)
    if tree.get("error"):
        return None, f"DuckDB cannot serialise the query: {str(tree.get('error_message', ''))[:120]}"
    if len(tree.get("statements", [])) != 1:
        return None, "embedded query is not exactly one SELECT"
    return tree, None


def _walk(node, out: list):
    if isinstance(node, dict):
        out.append(node)
        for v in node.values():
            _walk(v, out)
    elif isinstance(node, list):
        for v in node:
            _walk(v, out)


def ast_problems(tree: dict) -> list[str]:
    nodes: list = []
    _walk(tree, nodes)
    ctes = {str(e.get("key", "")).lower() for n in nodes if isinstance(n.get("cte_map"), dict)
            for e in n["cte_map"].get("map", []) if isinstance(e, dict)}
    probs = []
    for n in nodes:
        t = n.get("type")
        if t == "TABLE_FUNCTION":
            fn = (n.get("function") or {}).get("function_name", "?")
            probs.append(f"table function {fn!r} is not allowed (reads or executes outside the catalog)")
        elif t == "BASE_TABLE":
            schema, table, cat = (str(n.get("schema_name") or "").lower(), str(n.get("table_name") or ""),
                                  str(n.get("catalog_name") or ""))
            if cat:
                probs.append(f"catalog-qualified reference {cat}.{schema}.{table} is not allowed")
            elif not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", table):
                probs.append(f"table reference {table!r} is a path or string (replacement scan) - not allowed")
            elif not schema:
                if table.lower() not in ctes:
                    probs.append(f"unqualified table {table!r} is not a CTE - qualify it with an allowed schema")
            elif schema not in ALLOWED_SCHEMAS:
                probs.append(f"reference to schema {schema!r} is outside the allowlist {sorted(ALLOWED_SCHEMAS)}")
        if n.get("class") in ("FUNCTION", "WINDOW", "AGGREGATE") and "function_name" in n:
            name = str(n["function_name"]).lower()
            if n.get("is_operator") or not re.match(r"[a-z_]", name):
                continue
            if n.get("schema") or n.get("catalog"):
                probs.append(f"schema-qualified function {n.get('schema')}.{name} is not allowed")
            elif name not in ALLOWED_FUNCTIONS:
                probs.append(f"function {name!r} is not on the allowlist")
    return probs


def _serialize_many(queries: list[str]) -> dict[str, tuple[dict | None, str | None]]:
    """One DuckDB call for many queries (per-call overhead dominated large plans). Falls back per query."""
    out: dict[str, tuple[dict | None, str | None]] = {}
    uniq = list(dict.fromkeys(queries))
    if not uniq:
        return out
    rows = []
    for i in range(0, len(uniq), 200):  # json_serialize_sql needs a constant argument: inline escaped literals
        chunk = uniq[i:i + 200]
        lits = ", ".join("json_serialize_sql('" + q.replace("'", "''") + "')" for q in chunk)
        try:
            rows += list(zip(chunk, _con().execute(f"SELECT [{lits}]").fetchone()[0]))
        except duckdb.Error:
            continue  # checked one by one below
    for q, raw in rows:
        tree = json.loads(raw)
        if tree.get("error"):
            out[q] = (None, f"DuckDB cannot serialise the query: {str(tree.get('error_message', ''))[:120]}")
        elif len(tree.get("statements", [])) != 1:
            out[q] = (None, "embedded query is not exactly one SELECT")
        else:
            out[q] = (tree, None)
    for q in uniq:  # anything the batch did not return is checked on its own
        if q not in out:
            out[q] = _serialize(q)
    return out


def _pre(stmt: str, obj: str) -> tuple[list[str], str | None]:
    """Lexical, statement-count, shape and target checks. Returns (problems, embedded query or None)."""
    for pat, msg in _FORBIDDEN_LEX:
        if pat.search(stmt):
            return [msg], None
    try:
        parsed = _con().extract_statements(stmt)
    except duckdb.Error as e:
        return [f"DuckDB cannot parse the statement: {str(e).splitlines()[0][:120]}"], None
    if len(parsed) != 1:
        return [f"{len(parsed)} statements in one string - exactly one is allowed"], None
    for kind, rx in _SHAPES:
        m = rx.match(stmt)
        if m:
            break
    else:
        return [f"statement shape not allowed in a plan: {stmt.strip()[:40]!r}"], None
    probs = []
    if parsed[0].type.name != _ALLOWED_TYPES[kind]:
        probs.append(f"DuckDB sees a {parsed[0].type.name} statement, expected {_ALLOWED_TYPES[kind]}")
    target = _canon_name(m.group("name"))
    if target != obj.lower():
        probs.append(f"writes {target!r}, not the item's object {obj!r}")
    query = None
    if kind in ("view", "ctas"):
        query = m.group("query")
    elif kind == "insert":
        query = f"SELECT * FROM (VALUES {m.group('values')}) AS v"
    elif kind == "delete" and m.group("cond"):
        query = f"SELECT 1 FROM {m.group('name')} WHERE {m.group('cond')}"
    return probs, query


def check_many(pairs: list[tuple[str, str]]) -> dict[tuple[str, str], list[str]]:
    """statement_problems for many (statement, object) pairs, with one batched DuckDB serialisation."""
    pre = {}
    for stmt, obj in dict.fromkeys(pairs):
        pre[(stmt, obj)] = ([], None) if not (stmt or "").strip() else _pre(stmt, obj)
    trees = _serialize_many([q for _, q in pre.values() if q is not None])
    out = {}
    for key, (probs, q) in pre.items():
        probs = list(probs)
        if q is not None:
            tree, err = trees[q]
            probs += [err] if err else ast_problems(tree)
        out[key] = sorted(set(probs))
    return out


def statement_problems(stmt: str, obj: str) -> list[str]:
    return check_many([(stmt or "", obj)])[(stmt or "", obj)]
